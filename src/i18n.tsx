const enToAr = Object.fromEntries(Object.entries(arToEn).map(([ar,en]) => [en,ar])) as Record<string,string>;

function translateValue(value: string, dict: Record<string, string>) {
  let result = value;
  const keys = Object.keys(dict).sort((a,b) => b.length-a.length);
  for (const key of keys) {
    if (result.includes(key)) result = result.split(key).join(dict[key]);
  }
  return result;
}

function translateTree(root: ParentNode, language: Language) {
  const dict = language === "en" ? arToEn : enToAr;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes: Text[] = [];
  while (walker.nextNode()) {
    const node = walker.currentNode as Text;
    if (node.parentElement?.closest("script,style,code,pre,textarea,[contenteditable='true']")) continue;
    nodes.push(node);
  }
  for (const node of nodes) {
    const original = node.nodeValue ?? "";
    const translated = translateValue(original, dict);
    if (translated !== original) node.nodeValue = translated;
  }
  const elements = root.querySelectorAll<HTMLElement>("[placeholder],[title],[aria-label],[alt]");
  elements.forEach(el => {
    for (const attr of ["placeholder","title","aria-label","alt"]) {
      const current = el.getAttribute(attr);
      if (current) {
        const translated = translateValue(current, dict);
        if (translated !== current) el.setAttribute(attr, translated);
      }
    }
  });
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    try { return localStorage.getItem("future-platform-language") === "en" ? "en" : "ar"; } catch { return "ar"; }
  });
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    document.documentElement.dataset.language = language;
    const run = () => translateTree(document, language);
    run();
    const observer = new MutationObserver(() => run());
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
    try { localStorage.setItem("future-platform-language", language); } catch {}
    return () => observer.disconnect();
  }, [language]);
  const value = useMemo(() => ({ language, toggleLanguage: () => setLanguage(v => v === "ar" ? "en" : "ar") }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
export function useLanguage() { return useContext(LanguageContext); }
